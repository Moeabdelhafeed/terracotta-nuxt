import 'package:flutter/foundation.dart';
import 'package:intl/intl.dart';

/// One ISO-4217 currency — drives the amount field's decimal cap
/// (JOD = 3, USD = 2, JPY = 0), symbol placement and picker rows.
@immutable
class Currency {
  const Currency({
    required this.code,
    required this.symbol,
    required this.name,
    required this.nameAr,
    this.countryCode,
    this.decimalDigits = 2,
    this.symbolBeforeAmount = true,
  });

  /// ISO-4217 alpha code (`'JOD'`).
  final String code;

  /// ISO-3166 country for the flag + locale-default lookup (`'JO'`,
  /// `'EU'` for the euro). Null for multi-country currencies with no
  /// single flag (XOF / XAF / XPF / XCD).
  final String? countryCode;

  /// Display symbol (`'JD'`, `'$'`, `'€'`).
  final String symbol;

  /// English name.
  final String name;

  /// Arabic name. Deliberately INLINE, not ARB: `AmountToWords.money`
  /// takes a forced `arabic:` flag (Arabic cheque wording while the UI
  /// runs in English) and ARB lookups are bound to the loaded locale
  /// bundle — an ARB-backed name couldn't serve the cross-locale
  /// engine. Display paths still localize via [displayName].
  final String nameAr;

  /// Minor-unit digits per ISO-4217 (JOD/KWD/BHD/OMR/TND = 3, JPY/KRW
  /// = 0). The amount formatter caps typing at this.
  final int decimalDigits;

  /// `$ 49.99` vs `49.99 د.أ`.
  final bool symbolBeforeAmount;

  /// Name matching the active locale.
  String get displayName =>
      Intl.getCurrentLocale().startsWith('ar') ? nameAr : name;

  @override
  bool operator ==(Object other) =>
      identical(this, other) || other is Currency && other.code == code;

  @override
  int get hashCode => code.hashCode;
}

