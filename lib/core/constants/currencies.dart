  /// The currency of an ISO-3166 country (`'JO'` → JOD, `'DE'` → EUR).
  /// Null when unknown — callers fall back to [defaultCurrency].
  static Currency? byCountry(String countryIso) {
    final upper = countryIso.toUpperCase();
    if (_eurozone.contains(upper)) return byCode('EUR');
    for (final c in all) {
      if (c.countryCode == upper) return c;
    }
    return null;
  }

